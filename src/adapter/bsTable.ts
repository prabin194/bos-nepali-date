export function getMonthLen(year: number, month: number): number {
  const idx = (year - BS_MIN_YEAR) * 12 + month - 1;
  if (idx < 0 || idx >= bsMonthData.length) {
    throw new Error('BS year ' + year + ' not supported by adapter.');
  }
  return bsMonthData[idx];
}

export function hasYear(year: number): boolean {
  const idx = (year - BS_MIN_YEAR) * 12;
  return idx >= 0 && idx < bsMonthData.length - 11;
}

